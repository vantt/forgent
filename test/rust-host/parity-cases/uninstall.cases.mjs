// Uninstall parity table: every `fgos uninstall` call the base release answers, on a fresh world per entry (a git
// project with its own HOME, TMPDIR and state root). Each fixture is prepared by the base release's own installers
// (the hook table, the git hooks wiring) so both entries start from the same bytes the product wrote. Calls are
// compared on exit status, the answer's data, stderr and, for the cases that change anything, what the run left on
// disk (project and HOME). The host never starts Node for this verb.
//
// Steps: `{ do: <action> }` prepares the world, `{ args, cwd? }` is one call. `cwd`: `repo`, `sub`, `outside` (a
// directory that is no repository), `linked` (a linked worktree of `repo`), `payload` (the checkout the entry's
// own payload sits in: a source checkout).
