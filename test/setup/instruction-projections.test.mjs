test('instruction projection options reject unsupported host adapters and escaping destinations', () => {
  const root = mkTempDir('fgos-instruction-projection-options-');
  writeInstructionFile(
    root,
    'law.md',
    'id: projection-law\nkind: law\ntitle: Projection Law',
    '# Projection Law\nRender me.',
  );

  assert.throws(
    () => computeInstructionProjection(root, { host: 'claude' }),
    /Unsupported instruction projection host/,
  );
  assert.throws(
    () => materializeInstructionProjection(root, { destinationPath: '../AGENTS.md' }),
    /must stay inside the project root/,
  );
  assert.throws(
    () => materializeInstructionProjection(root, { destinationPath: path.join(root, 'AGENTS.md') }),
    /must be relative/,
  );
  assert.throws(
    () => materializeInstructionProjection(root, { destinationPath: '.' }),
    /must stay inside the project root/,
  );
  assert.throws(
    () => materializeInstructionProjection(root, { target: 'domain:/../../../../../escaped/pwned' }),
    /Effective instruction set key must be a portable file stem/,
  );
  assert.equal(fs.existsSync(path.join(path.dirname(root), 'escaped', 'pwned.json')), false);
  const packageJson = path.join(root, 'package.json');
  fs.writeFileSync(packageJson, '{"name":"fixture"}\n', 'utf8');
  assert.throws(
    () => materializeInstructionProjection(root, { target: 'domain:/../../../../package' }),
    /Effective instruction set key must be a portable file stem/,
  );
  assert.equal(fs.readFileSync(packageJson, 'utf8'), '{"name":"fixture"}\n');
});

test('instruction projection materialization rejects symlinked destinations', () => {
  const root = mkTempDir('fgos-instruction-projection-symlink-root-');
  const outside = mkTempDir('fgos-instruction-projection-symlink-outside-');
  const victim = path.join(outside, 'victim.md');
  fs.writeFileSync(victim, 'EXTERNAL HUMAN CONTENT\n', 'utf8');
  fs.symlinkSync(victim, path.join(root, 'AGENTS.md'));
  writeInstructionFile(
    root,
    'law.md',
    'id: projection-law\nkind: law\ntitle: Projection Law',
    '# Projection Law\nRender me.',
  );

  assert.throws(
    () => materializeInstructionProjection(root),
    /must not cross a symlink/,
  );
  assert.equal(fs.readFileSync(victim, 'utf8'), 'EXTERNAL HUMAN CONTENT\n');
});

test('instruction projection materialization rejects dangling symlinked projection paths', () => {
  const root = mkTempDir('fgos-instruction-projection-dangling-link-root-');
  const outside = mkTempDir('fgos-instruction-projection-dangling-link-outside-');
  const agentsVictim = path.join(outside, 'planted-agents.md');
  fs.symlinkSync(agentsVictim, path.join(root, 'AGENTS.md'));
  writeInstructionFile(
    root,
    'law.md',
    'id: projection-law\nkind: law\ntitle: Projection Law',
    '# Projection Law\nRender me.',
  );

  assert.throws(
    () => materializeInstructionProjection(root),
    /must not cross a symlink/,
  );
  assert.equal(fs.existsSync(agentsVictim), false);

  fs.rmSync(path.join(root, 'AGENTS.md'));
  const ledgerPath = path.join(root, PROJECTION_LEDGER_RELATIVE_PATH);
  fs.mkdirSync(path.dirname(ledgerPath), { recursive: true });
  const ledgerVictim = path.join(outside, 'planted-ledger.json');
  fs.symlinkSync(ledgerVictim, ledgerPath);
  assert.throws(
    () => materializeInstructionProjection(root),
    /must not cross a symlink/,
  );
  assert.equal(fs.existsSync(ledgerVictim), false);
});

