function mkTempDir(prefix) {
  return fs.mkdtempSync(path.join(os.tmpdir(), prefix));
}

function writeInstructionFile(root, name, frontmatter, body = '# Body\nInstruction text') {
  const dir = path.join(root, 'core', 'instructions');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, name), `---\n${frontmatter}\n---\n\n${body}\n`, 'utf8');
}

function compiledUnit(root, meta, body = '# Rule\nDo the thing.') {
  return compileInstructionUnit(meta, body, '', {
    projectRoot: root,
    fullPath: path.join(root, 'core', 'instructions', `${meta.id}.md`),
    sourcePath: `core/instructions/${meta.id}.md`,
    rootType: 'platform',
    rootOwner: 'core',
    knownOwners: new Set(['core']),
  });
}

function projectionCheck() {
  return DOCTOR_CHECKS.find((entry) => entry.id === 'instruction-projections-stale');
}

function projectionFix() {
  return FIX_REGISTRATIONS.find((entry) => entry.id === 'instruction-projections-stale');
}

function git(args, cwd) {
  return execFileSync('git', args, {
    cwd,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  }).trim();
}

test('renderPortableAgentsProjection renders a deterministic managed AGENTS.md block from the effective set', () => {
  const root = mkTempDir('fgos-instruction-projection-golden-');
  const set = composeInstructionSet([
    compiledUnit(root, {
      id: 'test-law',
      kind: 'law',
      title: 'Test Law',
      description: 'A deterministic law',
    }, '# Test Law\nAlways render through the effective set.'),
  ]);

  assert.equal(renderPortableAgentsProjection(set), [
    MANAGED_BLOCK_START,
    '<!-- generated by fgos instruction projection; edit canonical instruction sources, not this block -->',
    '<!-- effective-set: .fgos/instructions/effective/repo.json; key=repo; host=* -->',
    '',
    '## fgOS Effective Instructions',
    '',
    '### law',
    '',
    '#### Test Law',
    '',
    '- id: `test-law`',
    '- source: `core/instructions/test-law.md`',
    '',
    '# Test Law',
    'Always render through the effective set.',
    '',
    MANAGED_BLOCK_END,
    '',
  ].join('\n'));
});

test('materializeInstructionProjection writes effective JSON, managed AGENTS.md block, and projection ledger', () => {
  const root = mkTempDir('fgos-instruction-projection-materialize-');
  fs.writeFileSync(path.join(root, 'AGENTS.md'), '# Local Notes\n\nKeep this prose.\n', 'utf8');
  writeInstructionFile(
    root,
    'law.md',
    'id: projection-law\nkind: law\ntitle: Projection Law',
    '# Projection Law\nRender me.',
  );

  const result = materializeInstructionProjection(root);
  assert.equal(result.changed, true);

  const agents = fs.readFileSync(path.join(root, 'AGENTS.md'), 'utf8');
  assert.ok(agents.startsWith('# Local Notes\n\nKeep this prose.\n\n'));
  assert.match(agents, /<!-- fgos:instruction-projection:start -->/);
  assert.match(agents, /# Projection Law\nRender me\./);

  const effective = JSON.parse(fs.readFileSync(path.join(root, '.fgos/instructions/effective/repo.json'), 'utf8'));
  assert.deepEqual(effective.rules.map((rule) => rule.id), ['projection-law']);

  const ledger = JSON.parse(fs.readFileSync(path.join(root, PROJECTION_LEDGER_RELATIVE_PATH), 'utf8'));
  assert.equal(ledger.schemaVersion, 1);
  assert.equal(ledger.projections.length, 1);
  assert.equal(ledger.projections[0].destinationPath, 'AGENTS.md');
  assert.equal(ledger.projections[0].ownership, 'managed-block');
});

