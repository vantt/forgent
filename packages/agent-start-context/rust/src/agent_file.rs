//! An agent file (`.claude/agents/<persona>.md`): one persona's definition projected for an agent CLI, frontmatter
//! then body. It carries no rule: rules reach every agent through the standing sheet, not through its agent file.

use fgos_yaml_doc::{write_frontmatter, Value};

use crate::compose::{block, Candidate};
use crate::persona::{PersonaFields, PersonaLookup};
use crate::ports::Ports;
use crate::request::{Refusal, RefusalCode, StartRequest};

/// The one block of an agent-file start. A persona the host does not find, or cannot read, refuses the start.
pub(crate) fn layout(
    request: &StartRequest,
    ports: &Ports<'_>,
) -> Result<(Vec<Candidate>, Vec<String>), Refusal> {
    let persona = request.facts.get("persona").cloned().unwrap_or_default();
    let invalid = |message: String| Refusal::new(RefusalCode::StartFactValueInvalid, &message);
    let fields = match ports.personas.map(|p| p.lookup(&persona)) {
        Some(PersonaLookup::Found(fields)) => fields,
        Some(PersonaLookup::NotFound) => {
            return Err(invalid(format!(
                "no agent definition names the persona \"{persona}\""
            )))
        }
        Some(PersonaLookup::Failed(line)) => return Err(invalid(line)),
        None => {
            return Err(Refusal::new(
                RefusalCode::StartDeliveryUnsupported,
                "an agent file needs the host's persona definitions, and none are wired",
            ))
        }
    };
    let text = agent_file(&persona, &fields).map_err(invalid)?;
    Ok((
        vec![Candidate {
            block: block("agent-file", format!("persona:{persona}"), text),
            required: true,
        }],
        Vec::new(),
    ))
}

/// The whole file: YAML frontmatter (name, description, the comma-joined tools Claude Code reads, the skills when
/// declared), then the role, the generated-file notice, the persona and the decision boundary.
pub fn agent_file(name: &str, fields: &PersonaFields) -> Result<String, String> {
    let mut meta = vec![
        ("name".to_owned(), Value::Str(name.to_owned())),
        (
            "description".to_owned(),
            Value::Str(fields.description.clone()),
        ),
        ("tools".to_owned(), Value::Str(fields.tools.join(", "))),
    ];
    if !fields.skills.is_empty() {
        meta.push((
            "skills".to_owned(),
            Value::Seq(fields.skills.iter().cloned().map(Value::Str).collect()),
        ));
    }
    let mut body = vec![
        format!("# {}", fields.role),
        String::new(),
        format!(
            "> Generated by `scripts/project-agents.mjs` from `{}` -- do not hand-edit this file; edit the source yaml and re-run the projection script instead.",
            fields.source
        ),
        String::new(),
        "## Persona".into(),
        String::new(),
        format!("- **Voice:** {}", fields.voice),
        format!("- **Style:** {}", fields.style),
        format!("- **Archetype:** {}", fields.archetype),
        String::new(),
        "## Decision Boundary".into(),
        String::new(),
        "**Can decide:**".into(),
    ];
    body.extend(fields.can_decide.iter().map(|item| format!("- {item}")));
    body.push(String::new());
    body.push("**Must escalate:**".into());
    body.extend(fields.must_escalate.iter().map(|item| format!("- {item}")));
    write_frontmatter(meta, &format!("\n{}\n", body.join("\n")), &fields.source)
        .map_err(|e| format!("persona \"{name}\" cannot be written as an agent file: {e}"))
}
