// command-registry.mjs — the single source of truth for the fgos CLI's
// machine-readable verb manifest (`fgos --help --json`), mirroring the
// `.bee/bin/lib/command-registry.mjs` precedent (entry-standardization P37,
// deliverable b).
//
// Pure data only — no imports of verb logic (src/state, src/runner, etc.), so
// this module sits at the `kernel` layer in docs/architecture-manifest.json:
// `bin/fgos.mjs` (entry) importing it is a downward import, and this file can
// never import back up into anything that would create a cycle.
//
// Each entry's `parameters` field is JSON-Schema in the same
// {type:"object", properties, required} shape bee's registry uses — the
// manifest is zero-translation for any tool-schema-based agent.
//
// `touchesState`/`externalEffect` (str46-io-contract D4, superseding the
// prior single `access` field) are two independent per-verb declarations: the
// former is true for any verb that ever appends an event or overwrites
// `.fgos/state.json`; the latter is true only for a verb with a real effect
// OUTSIDE `.fgos/` (today: `review --github`/`approve --github`, which touch
// a real GitHub PR). A verb with more than one sub-mode (review, evolve,
// session) is classified by its most-privileged effect on each axis — e.g.
// `evolve` with no flags is a pure read but `evolve --submit` appends a work
// item, so the whole verb declares `touchesState: true`. Both flags are
// declarations only: P37/this cell do not wire them into dispatch/authz
// (that is P38's job).
//
// `paginated` (str46-io-contract D5/D35) declares whether the verb's result
// accepts --cursor/--limit (opaque cursor, per cursor.mjs) — true only for
// `ready`/`triage`/`evolve`/`list`, the four verbs whose result can grow
// unboundedly with data. Every entry carries this field (even the 30 that
// are `false`) so a transport can read pagination support machine-readably
// instead of guessing per verb.
//
// `requiresExistingStore` (tsk-4fu-2) is narrower than `touchesState`: true
// only for a verb whose handler actually reads/writes through the CLI's own
// `dataDir()` (the strict, cwd-resolved `.fgos/` — bin/fgos.mjs's `dir`
// param). A verb can be `touchesState: true` without this — `session`
// writes `.fgos/sessions.json` through its own independent, git-resolved
// path (session.mjs, D10 symlink actor), never through `dir`, and `setup`
// touches the shared config file/shell rc files/git hooks, never `.fgos/` at
// all — so gating either of those on `dir`'s existence would refuse for a
// reason that has nothing to do with what they actually do. `init` is also
// `false` here despite being the one verb that legitimately creates
// `.fgos/`: it gets the opposite check (refuse inside a linked worktree,
// via `isMainWorktree`), not this one. Every entry carries this field, same
// discipline as `paginated` above.

