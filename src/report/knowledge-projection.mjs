// src/report/knowledge-projection.mjs
// Pure projection generator for knowledge registry (JSON + Markdown).

export function computeKnowledgeProjection(view) {
  const topics = view?.topics ?? {};
  const docs = view?.docs ?? {};

  const jsonContent = JSON.stringify(
    {
      topics: Object.values(topics),
      docs: Object.values(docs),
    },
    null,
    2
  ) + '\n';

  let md = `---
generated: true
---
# Knowledge Registry Index

> **WARNING**: This file is generated by \`fgos doc-registry\` — never hand-edit. Any manual edit will be overwritten.

`;

  md += `## Topics\n\n`;
  for (const topic of Object.values(topics)) {
    md += `### ${topic.purposeTitle || topic.topicId} (\`${topic.topicId}\`)\n`;
    md += `- Status: **${topic.status}**\n`;
    md += `- Purpose Slug: \`${topic.purposeSlug}\`\n`;
    if (topic.lineage) {
      md += `- Lineage: ${JSON.stringify(topic.lineage)}\n`;
    }
    const topicDocs = Object.values(docs).filter((d) => d.topicId === topic.topicId);
    if (topicDocs.length === 0) {
      md += `- *No doc slots registered for this topic*\n`;
    } else {
      md += `- Docs:\n`;
      for (const d of topicDocs) {
        md += `  - \`${d.role}\` (${d.docLifecycle}): \`${d.currentPath}\`\n`;
        if (d.aliases && d.aliases.length > 0) {
          md += `    - Aliases: ${d.aliases.map((a) => `\`${a}\``).join(', ')}\n`;
        }
      }
    }
    md += `\n`;
  }

  return { jsonContent, mdContent: md };
}
